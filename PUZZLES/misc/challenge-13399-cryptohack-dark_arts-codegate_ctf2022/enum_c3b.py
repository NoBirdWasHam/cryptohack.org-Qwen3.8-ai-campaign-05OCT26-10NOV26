# RUN#2 SOLUTION CANDIDATE: parity-coset enumeration for Challenge 3.
#
# Reformulation (exact): find k in {0..3}^n, m in Z^T with
#   r_j := k.d_j - 5*m_j in S_{b_j},  S_0={0,2,4}, S_1={1,3}.
# Observation (self-derived): with center t_j = 2 - b_j:
#   r_j in S_{b_j}  <=>  (r_j - t_j) even  AND  (r_j - t_j)^2 <= 4
# so "parity of the residue" is a lattice/coset condition, not a norm condition.
# Let Lambda = rowspan{d_i} + 5Z^T = {k.D - 5m : k in Z^n, m in Z^T} (rank T, det 5^{T-n}).
# Target coset C = {v in Lambda : v_j = b_j (mod 2)} = v0 + Lambda2 with
#   v0 = -5b, Lambda2 = Lambda ∩ 2Z^T, generated by {phi(d_i)} ∪ {10 e_j},
#   phi(d) := d - 5*(d mod 2) (even vector; phi additive mod 10Z^T).
# Enumerate ALL points of C within radius^2 R2 around target t (true dist^2 ~ 2.33T,
# max 4T), then filter each by the offset-set test + recover k over Z5 + box {0..3}^n.
# Gaussian heuristic: expected spurious points ~ 4^n*(13/25)^T + 5^n*2^-T -> <1 at T~160.
import hashlib, sys, time, itertools, random
from fpylll import IntegerMatrix, LLL, GSO, Enumeration

S = {0: {0, 2, 4}, 1: {1, 3}}
MOD5INV = {1: 1, 2: 3, 3: 2, 4: 4}

def digits5(x):
    x = int.from_bytes(hashlib.sha256(str(x).encode()).digest(), "big")
    d = []
    for _ in range(64):
        d.append(x % 5); x //= 5
    return d

def make_instance(n, T, seed=1):
    rng = random.Random(seed)
    k = [rng.randrange(4) for _ in range(n)]
    D, b = [], []
    while len(D) < T:
        x = rng.randrange(2**256)
        d = digits5(x)[:n]
        D.append(d)
        b.append((sum(k[i]*d[i] for i in range(n)) % 5) % 2)
    return k, D, b

def basis_from_gens(gens, ncols):
    """Z-basis of lattice spanned by dependent generator rows: fplll LLL handles
    linear dependence and pushes zero rows to the top."""
    B = IntegerMatrix(len(gens), ncols)
    for i, g in enumerate(gens):
        for j, x in enumerate(g):
            B[i, j] = x
    LLL.reduction(B)
    rows = [[B[i, j] for j in range(ncols)] for i in range(len(gens))
            if any(B[i, j] for j in range(ncols))]
    return rows

def solve_z5(D, w, n, T):
    inv = MOD5INV
    M = [[D[j][i] % 5 for j in range(T)] + [w[j] % 5] for i in range(n)]
    row = 0; piv = {}
    for j in range(T):
        p = None
        for r in range(row, n):
            if M[r][j] % 5: p = r; break
        if p is None: continue
        M[row], M[p] = M[p], M[row]
        iv = inv[M[row][j] % 5]
        M[row] = [x*iv % 5 for x in M[row]]
        for r in range(n):
            if r != row and M[r][j] % 5:
                f = M[r][j] % 5
                M[r] = [(a - f*c) % 5 for a, c in zip(M[r], M[row])]
        piv[row] = j; row += 1
        if row == n: break
    if row < n: return None
    k = [0]*n
    for r, j in piv.items(): k[j] = M[r][T] % 5
    for j in range(T):
        if sum(k[i]*D[j][i] for i in range(n)) % 5 != w[j] % 5:
            return None
    return k

def parity_coset_solve(D, b, n, T, R2=None, verbose=False):
    """Returns (list of surviving k tuples, nodes, secs)."""
    t0 = time.time()
    gens = []
    for i in range(n):
        w = [D[j][i] % 5 for j in range(T)]
        gens.append([w[j] - 5*(w[j] % 2) for j in range(T)])
    for j in range(T):
        g = [0]*T; g[j] = 10; gens.append(g)
    basis = basis_from_gens(gens, T)
    if len(basis) != T:
        raise RuntimeError(f"rank {len(basis)} != T {T}")
    if verbose: print(f"  basis ok, entries max {max(abs(x) for r in basis for x in r)}")
    B = IntegerMatrix(T, T)
    for i, row in enumerate(basis):
        for j, x in enumerate(row):
            B[i, j] = x
    MG = GSO.Mat(B)
    MG.update_gso()
    e = Enumeration(MG)
    tgt = [2.0 + 4.0*bb for bb in b]      # ambient target t - v0 = (2 - b) + 5b
    # fpylll Enumeration target is in BASIS (row) coordinates: x with x*B = tgt
    import sympy
    Bs = sympy.Matrix(basis)
    xs = Bs.solve(sympy.Matrix(tgt))
    tgt_c = [float(v) for v in xs]
    if R2 is None: R2 = int(round(2.8*T))
    sols = e.enumerate(0, T, R2, 0, target=tgt_c)
    nodes = e.get_nodes()
    out = []
    for coefs, dist2 in sols:
        vv = [int(round(sum(float(coefs[r])*B[r, j] for r in range(T)))) - 5*b[j] for j in range(T)]
        ok = True
        for j in range(T):
            if (vv[j] - (2 - b[j])) % 2 != 0 or (vv[j] - (2 - b[j]))**2 > 4: ok = False; break
            if vv[j] % 5 not in S[b[j]]: ok = False; break
        if not ok: continue
        k = solve_z5(D, [x % 5 for x in vv], n, T)
        if k is None: continue
        if any(kk > 3 for kk in k): continue
        if all((sum(k[i]*D[j][i] for i in range(n)) % 5) % 2 == b[j] for j in range(T)):
            out.append(tuple(k))
    return out, nodes, time.time() - t0

def brute(k_true, D, b, n, T):
    surv = []
    for kk in itertools.product(range(4), repeat=n):
        if all((sum(kk[i]*D[j][i] for i in range(n)) % 5) % 2 == b[j] for j in range(T)):
            surv.append(tuple(kk))
    return surv

if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "toy":
        n, T, seed = int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
        R2f = float(sys.argv[5]) if len(sys.argv) > 5 else 2.8
        k, D, b = make_instance(n, T, seed)
        bf = brute(k, D, b, n, T)
        cands, nodes, secs = parity_coset_solve(D, b, n, T, R2=int(R2f*T))
        print(f"n={n} T={T} seed={seed}: brute={len(bf)} enum={len(cands)} nodes={nodes} {secs:.2f}s true_in={tuple(k) in cands} exact={set(cands)==set(bf)}")
    elif mode == "full":
        T, seed = int(sys.argv[2]), int(sys.argv[3])
        R2f = float(sys.argv[4]) if len(sys.argv) > 4 else 2.8
        k, D, b = make_instance(64, T, seed)
        cands, nodes, secs = parity_coset_solve(D, b, 64, T, R2=int(R2f*T), verbose=True)
        print(f"n=64 T={T} seed={seed}: enum={len(cands)} nodes={nodes} {secs:.1f}s true_in={tuple(k) in cands}"
              + (f" sol_correct={cands[0]==tuple(k)}" if len(cands)==1 else ""))
