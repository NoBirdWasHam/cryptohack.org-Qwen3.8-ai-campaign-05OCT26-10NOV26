# F_{p^2} = F_p[i], i^2 = -1
def cadd(a, b): return ((a[0]+b[0]) % p, (a[1]+b[1]) % p)
def csub(a, b): return ((a[0]-b[0]) % p, (a[1]-b[1]) % p)
def cmul(a, b): return ((a[0]*b[0] - a[1]*b[1]) % p, (a[0]*b[1] + a[1]*b[0]) % p)
def csq(a): return cmul(a, a)
def cinv(a):
    d = pow((a[0]*a[0] + a[1]*a[1]) % p, p-2, p)
    return (a[0]*d % p, (-a[1]) * d % p)
def cneg(a): return ((-a[0]) % p, (-a[1]) % p)
CI = (0, 1)
def cpow(a, k):
    r = (1, 0)
    while k:
        if k & 1: r = cmul(r, a)
        a = cmul(a, a); k >>= 1
    return r

# EC over F_{p^2}: y^2 = x^3 + A x + B, A,B consts; point (x,y) or None (O)
def epadd(P, Q, A, B):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2:
        if cadd(y1, y2) == (0, 0): return None
        lam = cmul(cadd(cmul((3,0), csq(x1)), A), cinv(cmul((2,0), y1)))
    else:
        lam = cmul(csub(y2, y1), cinv(csub(x2, x1)))
    x3 = csub(csub(csq(lam), x1), x2)
    y3 = csub(cmul(lam, csub(x1, x3)), y1)
    return (x3, y3)
def emul(k, P, A, B):
    R = None
    while k:
        if k & 1: R = epadd(R, P, A, B)
        P = epadd(P, P, A, B); k >>= 1
    return R
def oncurve(P, A, B):
    if P is None: return True
    x, y = P
    return csq(y) == cadd(cadd(cmul(csq(x), x), cmul(A, x)), B)

def velu_step(E, Q, mult=1):
    """E=(A,B); kernel generated by Q of order `mult` (2 or 3). Returns (E', phi).
    phi(P) via x' = x + t/(x-xQ), y' = y*(1 - u/(x-xQ)^2) summed over +- reps."""
    A, B = E
    if mult == 2:
        reps = [Q]
    else:
        reps = [Q]  # +-Q pair counted once
    ts = []
    us = []
    for (qx, qy) in reps:
        t = cadd(cmul((3,0), csq(qx)), A)
        u = cmul((4,0), csq(qy))
        ts.append(t); us.append(u)
    A2 = csub(A, cmul((5,0), __import__('functools').reduce(cadd, ts, (0,0))))
    B2 = csub(B, cmul((7,0), __import__('functools').reduce(cadd, (cadd(u, cmul(qx, t)) for (qx, qy), t, u in zip(reps, ts, us)), (0,0))))
    def phi(P):
        if P is None: return None
        x, y = P
        xs = x; ys_factor = (1, 0)
        for (qx, qy), t, u in zip(reps, ts, us):
            if x == qx and cadd(y, cneg(qy)) == (0, 0) or x == qx and cadd(y, qy) == (0, 0):
                return None  # P in kernel -> O
            d = csub(x, qx)
            xs = cadd(xs, cmul(t, cinv(d)))
            ys_factor = csub(ys_factor, cmul(u, cinv(csq(d))))
        return (xs, cmul(y, ys_factor))
    return (A2, B2), phi

def velu_chain(E, R, ell, e, extra_points):
    """Walk e steps of ell-isogeny with kernel <R> (order ell^e).
    R is carried forward through each isogeny. Returns (E_final, images of extra_points)."""
    pts = [R] + list(extra_points)
    for i in range(e):
        Rn = pts[0]
        Q = emul(ell**(e-1-i), Rn, *E)   # order ell on current curve
        E, phi = velu_step(E, Q, ell)
        pts = [phi(P) for P in pts]
    return E, pts[1:]

