from spongebob import PBOXES, SBOX, INIT

def spread_entry(i, x):
    # bit b of byte i (value x) lands at byte PBOXES[b][i], bit b -> 144-bit int
    v = 0
    for b in range(8):
        if (x >> b) & 1:
            j = PBOXES[b][i]
            v |= 1 << (8 * j + b)
    return v

lines = []
A = lines.append
A("/* auto-generated by gen_tables.py -- do not edit */")
A("#ifndef TABLES_H")
A("#define TABLES_H")
A("#include <stdint.h>")
A("static const uint8_t SBOX[256] = {" + ",".join(str(v) for v in SBOX) + "};")
A("static const uint8_t INIT[18] = {" + ",".join(str(v) for v in INIT) + "};")
A("static const uint8_t PB[8][18] = {" + ",".join("{" + ",".join(str(v) for v in row) + "}" for row in PBOXES) + "};")

# SPREAD[i][x] : 3 x uint64 (144-bit) spread of byte value x at source byte i
A("static const uint64_t SPREAD[18][256][3] = {")
for i in range(18):
    A("{")
    for x in range(256):
        v = spread_entry(i, x)
        w0 = v & 0xFFFFFFFFFFFFFFFF
        w1 = (v >> 64) & 0xFFFFFFFFFFFFFFFF
        w2 = v >> 128
        A("{0x%xULL,0x%xULL,0x%xULL}," % (w0, w1, w2))
    A("},")
A("};")

# CONST0: spread of INIT bytes 8..17 (fixed part of round-1 permute input)
c = 0
for i in range(8, 18):
    c |= spread_entry(i, INIT[i])
A("#define C0_0 0x%xULL" % (c & 0xFFFFFFFFFFFFFFFF))
A("#define C0_1 0x%xULL" % ((c >> 64) & 0xFFFFFFFFFFFFFFFF))
A("#define C0_2 0x%xULL" % (c >> 128))

# T1[i][x] for i<8: spread of (INIT[i]^x)  (round-1 folded head)
A("static const uint64_t T1[8][256][3] = {")
for i in range(8):
    A("{")
    for x in range(256):
        v = spread_entry(i, INIT[i] ^ x)
        A("{0x%xULL,0x%xULL,0x%xULL}," % (v & 0xFFFFFFFFFFFFFFFF, (v >> 64) & 0xFFFFFFFFFFFFFFFF, v >> 128))
    A("},")
A("};")
A("#endif")

open("tables.h", "w").write("\n".join(lines) + "\n")
print("wrote tables.h", len("\n".join(lines)))
